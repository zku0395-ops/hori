// ぶんすう さがし カード の データ
// セットA・B・C は おなじ 50まい です（番号も おなじ。A-1・B-1・C-1 は おなじ 図）。
// 図は どれも 4×6マス。オレンジは いつも 1つの 形で、のこりは できるだけ オレンジに 近い 形で 区切ります。
// 全体の 1/4 の 大きさ（6マス）の オレンジは、1セットに 5まい だけ です。
// おなじ 大きさに わける カードは、どの パーツも 重ねると ぴったり 同じ形に なります（向きを かえたり うらがえしたり して よい）。
// p：区切った形（r＝長方形 [左,上,右,下]、g＝ななめの線のある形 [[x,y],…]、f:1＝オレンジ）
(function () {
  var W = 6, H = 4;
  function R(x0, y0, x1, y1, f) { var o = { r: [x0, y0, x1, y1] }; if (f) o.f = 1; return o; }
  function G(pts, f) { var o = { g: pts }; if (f) o.f = 1; return o; }
  // a×b の 形で 全体を 区切り、(fx,fy) から はじまる 形に 色を ぬる
  function grid(a, b, fx, fy) {
    var out = [];
    for (var y = 0; y < H; y += b) for (var x = 0; x < W; x += a) out.push(R(x, y, x + a, y + b, x === fx && y === fy));
    return out;
  }
  function X8(fill) {  // ×と 十字の 線（8つの 三角形）
    var c = [3, 2], P = [[0, 0], [3, 0], [6, 0], [6, 2], [6, 4], [3, 4], [0, 4], [0, 2]], out = [];
    for (var i = 0; i < 8; i++) out.push(G([P[i], P[(i + 1) % 8], c], fill === i));
    return out;
  }
  // 1/4（6マス）… 5まい
  var Q = {
    rows: grid(6, 1, 0, 0),                                            // よこの 帯 4つ
    blocks: grid(3, 2, 3, 2),                                          // 3×2 の 長方形 4つ
    triV: [G([[0, 0], [3, 0], [3, 4]]), G([[0, 0], [3, 4], [0, 4]], 1), G([[3, 0], [6, 0], [6, 4]]), G([[3, 0], [6, 4], [3, 4]])], // たて半分を ななめに（三角形 4つ）
    triH: [G([[0, 0], [6, 0], [6, 2]], 1), G([[0, 0], [6, 2], [0, 2]]), G([[0, 2], [6, 2], [6, 4]]), G([[0, 2], [6, 4], [0, 4]])], // よこ半分を ななめに（三角形 4つ）
    rows3: grid(6, 1, 0, 2)                                            // よこの 帯 4つ（3ばんめ）
  };

  var LIST = [
    // 1
    grid(2, 4, 0, 0),                                                  // 1/3
    [R(0, 0, 3, 4, 1), R(3, 0, 6, 4)],                                 // 1/2
    grid(1, 4, 0, 0),                                                  // 1/6
    Q.rows,                                                            // 1/4
    [R(0, 0, 2, 4), R(2, 0, 3, 4, 1), R(3, 0, 4, 4), R(4, 0, 6, 4)],   // ×（4つに わけたが おなじ 大きさで ない）
    grid(3, 1, 0, 0),                                                  // 1/8
    grid(1, 2, 4, 0),                                                  // 1/12
    [R(0, 0, 6, 2, 1), R(0, 2, 6, 4)],                                 // 1/2
    // 9
    [R(0, 0, 4, 2, 1), R(0, 2, 4, 4), R(4, 0, 6, 4)],                  // 1/3（4×2 と 2×4。向きを かえると 同じ形）
    grid(2, 2, 2, 0),                                                  // 1/6
    [R(0, 0, 5, 1, 1), R(5, 0, 6, 1), R(0, 1, 5, 4), R(5, 1, 6, 4)],   // ×
    [G([[0, 0], [6, 0], [6, 4]], 1), G([[0, 0], [6, 4], [0, 4]])],     // 1/2（ななめ）
    Q.blocks,                                                          // 1/4
    grid(2, 4, 2, 0),                                                  // 1/3
    X8(5),                                                             // 1/8（×と 十字）
    [R(0, 0, 6, 1), R(0, 1, 6, 2), R(0, 2, 6, 4, 1)],                  // ×（3つに わけたが おなじ 大きさで ない）
    // 17
    [0, 2, 4].map(function (x) { return [G([[x, 0], [x + 2, 0], [x + 2, 4]], x === 2), G([[x, 0], [x + 2, 4], [x, 4]])]; }).reduce(function (a, b) { return a.concat(b); }), // 1/6（2×4 を ななめに：三角形 6つ）
    grid(2, 1, 2, 3),                                                  // 1/12
    [G([[0, 0], [4, 0], [2, 4], [0, 4]], 1), G([[4, 0], [6, 0], [6, 4], [2, 4]])], // 1/2（台形）
    [R(0, 0, 1, 1), R(1, 0, 6, 1), R(0, 1, 1, 4), R(1, 1, 6, 4, 1)],   // ×
    [R(2, 0, 6, 2), R(2, 2, 6, 4, 1), R(0, 0, 2, 4)],                  // 1/3（4×2 と 2×4。向きを かえると 同じ形）
    Q.triV,                                                            // 1/4
    grid(1, 4, 3, 0),                                                  // 1/6
    mixed8(2, 0),                                                      // 1/8（1×3 と 3×1。向きを かえると 同じ形）
    // 25
    [R(0, 0, 5, 2), R(5, 0, 6, 2), R(0, 2, 5, 4), R(5, 2, 6, 4, 1)],   // ×
    grid(2, 4, 4, 0),                                                  // 1/3
    [R(0, 0, 6, 2), R(0, 2, 6, 4, 1)],                                 // 1/2
    grid(1, 2, 0, 2),                                                  // 1/12
    [R(0, 0, 1, 4, 1), R(1, 0, 3, 4), R(3, 0, 6, 4)],                  // ×（3つに わけたが おなじ 大きさで ない）
    grid(2, 2, 4, 2),                                                  // 1/6
    grid(3, 1, 3, 2),                                                  // 1/8
    [R(0, 0, 4, 2), R(0, 2, 4, 4, 1), R(4, 0, 6, 4)],                  // 1/3（4×2 と 2×4。向きを かえると 同じ形）
    // 33
    [G([[0, 0], [6, 0], [2, 2]]), G([[6, 0], [6, 4], [2, 2]]), G([[6, 4], [0, 4], [2, 2]]), G([[0, 4], [0, 0], [2, 2]], 1)], // ×（×の 線が まんなかで ない）
    [G([[0, 0], [6, 0], [6, 3], [0, 1]]), G([[0, 1], [6, 3], [6, 4], [0, 4]], 1)], // 1/2（台形）
    grid(2, 1, 0, 1),                                                  // 1/12
    Q.triH,                                                            // 1/4
    grid(2, 2, 2, 2),                                                  // 1/6
    [R(3, 0, 6, 4, 1), R(0, 0, 3, 4)],                                 // 1/2
    [G([[0, 0], [4, 4], [0, 4]], 1), G([[0, 0], [6, 0], [6, 4], [4, 4]])], // ×（ななめの 線が かどを とおらない）
    [R(0, 0, 4, 2), R(0, 2, 4, 4), R(4, 0, 6, 4, 1)],                  // 1/3（4×2 と 2×4。向きを かえると 同じ形）
    // 41
    mixed8(3, 3),                                                      // 1/8（1×3 と 3×1。向きを かえると 同じ形）
    grid(1, 4, 5, 0),                                                  // 1/6
    [R(0, 0, 2, 2, 1), R(2, 0, 4, 2), R(0, 2, 4, 4), R(4, 0, 6, 4)],   // ×（4つに わけたが おなじ 大きさで ない）
    [G([[6, 0], [6, 4], [0, 4]], 1), G([[0, 0], [6, 0], [0, 4]])],     // 1/2（ななめ）
    grid(3, 1, 0, 3),                                                  // 1/8
    [R(0, 0, 2, 4, 1), R(2, 0, 6, 4)],                                 // ×（2つに わけたが おなじ 大きさで ない）
    Q.rows3,                                                           // 1/4
    grid(2, 2, 0, 2),                                                  // 1/6
    // 49
    grid(1, 2, 5, 2),                                                  // 1/12
    [R(0, 0, 2, 4), R(2, 0, 6, 2, 1), R(2, 2, 6, 4)]                   // 1/3（4×2 と 2×4。向きを かえると 同じ形）
  ];
  // 1/8：たての 1×3 が 6つ ＋ 下の よこの 3×1 が 2つ（向きを かえると 同じ形）
  function mixed8(fx, fy) {
    var out = [];
    for (var x = 0; x < 6; x++) out.push(R(x, 0, x + 1, 3, fy === 0 && fx === x));
    out.push(R(0, 3, 3, 4, fy === 3 && fx === 0), R(3, 3, 6, 4, fy === 3 && fx === 3));
    return out;
  }

  var cards = [];
  ['A', 'B', 'C'].forEach(function (s) {
    LIST.forEach(function (p, i) { cards.push({ id: s + '-' + (i + 1), w: W, h: H, p: JSON.parse(JSON.stringify(p)) }); });
  });
  window.BUNSU_CARDS = cards;
})();
