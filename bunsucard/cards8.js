// ぶんすう さがし カード（1/8）の データ
// 1/4・1/2 の カード（cards.js・cards2.js）と おなじ きまりで 作ります。
// セットA・B・C は おなじ 50まい です（番号も おなじ。A-1・B-1・C-1 は おなじ 図）。
// 図は どれも 4×6マス。オレンジは いつも 1つの 形で、のこりは できるだけ オレンジに 近い 形で 区切ります。
// 全体の 1/8 の 大きさ（3マス）の オレンジは、1セットに 5まい だけ です（5・14・23・37・44ばん）。
// おなじ 大きさに わける カードは、どの パーツも 重ねると ぴったり 同じ形に なります（向きを かえたり うらがえしたり して よい）。
// 「8つに わけたけれど 大きさが ちがう」カードを まぜています。
// p：区切った形（r＝長方形 [左,上,右,下]、g＝ななめの線のある形 [[x,y],…]、f:1＝オレンジ）
(function () {
  var W = 6, H = 4;
  function R(x0, y0, x1, y1, f) { var o = { r: [x0, y0, x1, y1] }; if (f) o.f = 1; return o; }
  function G(pts, f) {
    // おなじ 点が つづいたら 1つに する
    var g = pts.filter(function (p, i) { var q = pts[(i + pts.length - 1) % pts.length]; return p[0] !== q[0] || p[1] !== q[1]; });
    var o = { g: g }; if (f) o.f = 1; return o;
  }
  function grid(a, b, fx, fy) {
    var out = [];
    for (var y = 0; y < H; y += b) for (var x = 0; x < W; x += a) out.push(R(x, y, x + a, y + b, x === fx && y === fy));
    return out;
  }
  function X8(fill) {  // ×と 十字の 線（8つの 三角形）
    var c = [3, 2], P = [[0, 0], [3, 0], [6, 0], [6, 2], [6, 4], [3, 4], [0, 4], [0, 2]], out = [];
    for (var i = 0; i < 8; i++) out.push(G([P[i], P[(i + 1) % 8], c], fill === i));
    return out;
  }
  function mixed8(fx, fy) {  // たての 1×3 が 6つ ＋ 下の よこの 3×1 が 2つ（向きを かえると 同じ形）
    var out = [];
    for (var x = 0; x < 6; x++) out.push(R(x, 0, x + 1, 3, fy === 0 && fx === x));
    out.push(R(0, 3, 3, 4, fy === 3 && fx === 0), R(3, 3, 6, 4, fy === 3 && fx === 3));
    return out;
  }
  // よこに 1本の 線：(0,a) から (6,b)。which＝'top' か 'bottom' を オレンジに
  function cutH(a, b, which) {
    return [G([[0, 0], [6, 0], [6, b], [0, a]], which === 'top'), G([[0, a], [6, b], [6, 4], [0, 4]], which === 'bottom')];
  }
  // たてに 1本の 線：(a,0) から (b,4)。which＝'left' か 'right' を オレンジに
  function cutV(a, b, which) {
    return [G([[0, 0], [a, 0], [b, 4], [0, 4]], which === 'left'), G([[a, 0], [6, 0], [6, 4], [b, 4]], which === 'right')];
  }

  // 1/8（3マス）… 5まい
  var EIGHT = [
    grid(3, 1, 0, 0),                                                  // 3×1 の 帯 8つ
    mixed8(3, 3),                                                      // 1×3 と 3×1（向きを かえると 同じ形）
    X8(5),                                                             // ×と 十字の 線（三角形 8つ）
    [[0, 0], [3, 0], [0, 2], [3, 2]].map(function (o) {                // 3×2 を ななめに わけた 三角形 8つ
      var x = o[0], y = o[1];
      return [G([[x, y], [x + 3, y], [x + 3, y + 2]], x === 3 && y === 2), G([[x, y], [x + 3, y + 2], [x, y + 2]])];
    }).reduce(function (a, b) { return a.concat(b); }),
    [R(0, 0, 3, 1), R(3, 0, 6, 1)].concat([0, 1, 2, 3, 4, 5].map(function (x) { return R(x, 1, x + 1, 4, x === 1); })) // 上に 3×1 が 2つ ＋ 1×3 が 6つ
  ];
  var EIGHT_AT = [5, 14, 23, 37, 44];

  // おなじ 大きさに わけた カード（1/8 いがい）… 25まい
  var EQ = [
    [R(0, 0, 3, 4, 1), R(3, 0, 6, 4)],                                 // 1/2
    grid(2, 4, 0, 0),                                                  // 1/3
    grid(6, 1, 0, 0),                                                  // 1/4
    grid(1, 4, 0, 0),                                                  // 1/6
    grid(1, 2, 4, 0),                                                  // 1/12
    cutH(1, 3, 'bottom'),                                              // 1/2（台形）
    [R(0, 0, 4, 2, 1), R(0, 2, 4, 4), R(4, 0, 6, 4)],                  // 1/3（4×2 と 2×4）
    grid(3, 2, 3, 2),                                                  // 1/4
    grid(2, 2, 2, 0),                                                  // 1/6
    grid(2, 1, 2, 3),                                                  // 1/12
    cutV(6, 0, 'left'),                                                // 1/2（三角形）
    grid(2, 4, 4, 0),                                                  // 1/3
    [G([[0, 0], [3, 0], [3, 4]]), G([[0, 0], [3, 4], [0, 4]], 1), G([[3, 0], [6, 0], [6, 4]]), G([[3, 0], [6, 4], [3, 4]])], // 1/4（三角形 4つ）
    [0, 2, 4].map(function (x) { return [G([[x, 0], [x + 2, 0], [x + 2, 4]], x === 2), G([[x, 0], [x + 2, 4], [x, 4]])]; }).reduce(function (a, b) { return a.concat(b); }), // 1/6（三角形 6つ）
    grid(1, 2, 0, 2),                                                  // 1/12
    [R(0, 0, 6, 2, 1), R(0, 2, 6, 4)],                                 // 1/2
    [R(0, 0, 2, 4), R(2, 0, 6, 2, 1), R(2, 2, 6, 4)],                  // 1/3（2×4 と 4×2）
    [G([[0, 0], [6, 0], [6, 2]], 1), G([[0, 0], [6, 2], [0, 2]]), G([[0, 2], [6, 2], [6, 4]]), G([[0, 2], [6, 4], [0, 4]])], // 1/4（三角形 4つ）
    grid(2, 2, 4, 2),                                                  // 1/6
    grid(2, 1, 0, 1),                                                  // 1/12
    cutV(4, 2, 'left'),                                                // 1/2（台形）
    grid(2, 4, 2, 0),                                                  // 1/3
    grid(6, 1, 0, 2),                                                  // 1/4
    grid(1, 4, 3, 0),                                                  // 1/6
    grid(1, 2, 5, 2)                                                   // 1/12
  ];

  // おなじ 大きさに わけていない カード … 20まい（オレンジは 3マスに しない）
  function rows(split, fx, fy) { // 4つの 段を それぞれ split の ところで 2つに わける（8つ）
    var out = [];
    for (var y = 0; y < 4; y++) out.push(R(0, y, split, y + 1, fx === 0 && fy === y), R(split, y, 6, y + 1, fx === 1 && fy === y));
    return out;
  }
  var NG = [
    rows(4, 1, 0),                                                     // 8つ（4マスと 2マス。オレンジ 2マス）
    [G([[0, 0], [3, 0], [2, 2]]), G([[3, 0], [6, 0], [2, 2]]), G([[6, 0], [6, 2], [2, 2]], 1), G([[6, 2], [6, 4], [2, 2]]), G([[6, 4], [3, 4], [2, 2]]), G([[3, 4], [0, 4], [2, 2]]), G([[0, 4], [0, 2], [2, 2]]), G([[0, 2], [0, 0], [2, 2]])], // ×と 十字が まんなかで ない（4マス）
    [R(0, 0, 4, 1, 1), R(4, 0, 6, 1)].concat(grid(3, 1, -1, -1).slice(2)), // 8つ（1つめの 段だけ 4マスと 2マス。オレンジ 4マス）
    [R(0, 0, 1, 2, 1), R(0, 2, 1, 4), R(1, 0, 2, 4), R(2, 0, 3, 4), R(3, 0, 4, 4), R(4, 0, 5, 4), R(5, 0, 6, 2), R(5, 2, 6, 4)], // 8つ（2マスと 4マス。オレンジ 2マス）
    rows(2, 0, 1),                                                     // 8つ（2マスと 4マス。オレンジ 2マス）
    [0, 1, 2, 3].map(function (y) { return [G([[0, y], [2, y], [3, y + 1], [0, y + 1]], y === 2), G([[2, y], [6, y], [6, y + 1], [3, y + 1]])]; }).reduce(function (a, b) { return a.concat(b); }), // 8つ（ななめの 線。オレンジ 2.5マス）
    [R(0, 0, 2, 1), R(0, 1, 2, 2), R(2, 0, 4, 2, 1), R(4, 0, 6, 2), R(0, 2, 2, 4), R(2, 2, 4, 4), R(4, 2, 6, 4)], // 7つ（2マスと 4マス。オレンジ 4マス）
    grid(3, 1, -1, -1).slice(0, 6).concat([R(0, 3, 6, 4, 1)]),         // 7つ（3マスと 6マス。オレンジ 6マス）
    [R(0, 0, 1, 4, 1), R(1, 0, 2, 4), R(2, 0, 6, 2), R(2, 2, 6, 4)],   // 4つ（4マスと 8マス）
    [G([[0, 0], [6, 0], [6, 1]]), G([[0, 0], [6, 1], [6, 4]], 1), G([[0, 0], [6, 4], [0, 4]])], // かどからの 三角形 3つ（9マス）
    [R(0, 0, 2, 4, 1), R(2, 0, 6, 4)],                                 // 2つ（8マス）
    [R(0, 0, 2, 1, 1), R(2, 0, 6, 1)].concat(grid(3, 1, -1, -1).slice(2)), // 8つ（1つめの 段だけ 2マスと 4マス。オレンジ 2マス）
    [R(0, 0, 6, 2), R(0, 2, 3, 4, 1), R(3, 2, 6, 4)],                  // 3つ（6マスと 12マス）
    [G([[0, 0], [6, 0], [6, 4]]), G([[0, 0], [6, 4], [3, 4]]), G([[0, 0], [3, 4], [0, 4]], 1)], // 三角形 3つ（6マス）
    [R(0, 0, 1, 4), R(1, 0, 2, 2, 1), R(1, 2, 2, 4), R(2, 0, 6, 1), R(2, 1, 6, 2), R(2, 2, 6, 3), R(2, 3, 6, 4)], // 7つ（2マスと 4マス。オレンジ 2マス）
    [R(0, 0, 6, 1, 1), R(0, 1, 6, 2), R(0, 2, 6, 4)],                  // 3つ（6マス）
    [G([[0, 0], [6, 0], [2, 2]]), G([[6, 0], [6, 4], [2, 2]]), G([[6, 4], [0, 4], [2, 2]]), G([[0, 4], [0, 0], [2, 2]], 1)], // ×の 線が まんなかで ない（4マス）
    [R(0, 0, 5, 1, 1), R(5, 0, 6, 1), R(0, 1, 6, 4)],                  // 3つ（5マス）
    [R(0, 0, 1, 1, 1), R(1, 0, 6, 1), R(0, 1, 1, 4), R(1, 1, 6, 4)],   // 4つ（1マス）
    cutV(1, 2, 'left')                                                 // ななめ（6マス）
  ];

  // ならべる：1/8 は きめた ばしょ、ほかは「おなじ 大きさ」と「ちがう 大きさ」を まぜる
  var LIST = [], e = 0, n = 0, h = 0;
  for (var i = 1; i <= 50; i++) {
    if (EIGHT_AT.indexOf(i) >= 0) LIST.push(EIGHT[h++]);
    else if ((i % 9 === 2 || i % 9 === 4 || i % 9 === 7 || i % 9 === 0) && n < NG.length) LIST.push(NG[n++]);
    else if (e < EQ.length) LIST.push(EQ[e++]);
    else LIST.push(NG[n++]);
  }

  var cards = [];
  ['A', 'B', 'C'].forEach(function (s) {
    LIST.forEach(function (p, i) { cards.push({ id: s + '-' + (i + 1), w: W, h: H, p: JSON.parse(JSON.stringify(p)) }); });
  });
  window.BUNSU_CARDS_8 = cards;
})();
