  // ぶんを よみとる しくみ（アプリと 点検の ツールで つかう）
  //   node = { t:'text', s } | { t:'ruby', b, r } | { t:'tag', c, n, kids:[node] }
  // -------------------------------------------------------------------
  var TAGCAT = { t: 'itsu', p: 'doko', k: 'kimochi', o: 'oto', s: 'dare', n: 'dare' };
  function parse(str) {
    var i = 0;
    function run(stopAt) {
      var out = [], buf = '';
      var flush = function () { if (buf) { out.push({ t: 'text', s: buf }); buf = ''; } };
      while (i < str.length) {
        var ch = str[i];
        if (ch === stopAt) { i++; flush(); return out; }
        if (ch === '[') {
          var j = str.indexOf(']', i), body = str.slice(i + 1, j), k = body.indexOf(':');
          flush(); out.push({ t: 'ruby', b: body.slice(0, k), r: body.slice(k + 1) }); i = j + 1; continue;
        }
        if (ch === '{') {
          var m = /^\{([tpkosn])(\d?):/.exec(str.slice(i));
          if (m) {
            flush(); i += m[0].length;
            var kids = run('}');
            out.push({ t: 'tag', c: TAGCAT[m[1]], k: m[1], n: m[2] ? Number(m[2]) : 0, kids: kids });
            continue;
          }
        }
        buf += ch; i++;
      }
      flush();
      return out;
    }
    return run(null);
  }
  function plain(nodes, yomi) {
    return nodes.map(function (n) { return n.t === 'text' ? n.s : n.t === 'ruby' ? (yomi ? n.r : n.b) : plain(n.kids, yomi); }).join('');
  }
  // タグの ついた ところを ぜんぶ ならべる（行の ばんごう つき）
  function spans(lines) {
    var out = [];
    lines.forEach(function (ln, li) {
      (function walk(nodes) {
        nodes.forEach(function (n) {
          if (n.t !== 'tag') return;
          out.push({ line: li, c: n.c, k: n.k, n: n.n, base: plain(n.kids), yomi: plain(n.kids, true), node: n });
          walk(n.kids);
        });
      })(typeof ln === 'string' ? parse(ln) : ln);
    });
    return out;
  }
  D.parse = parse; D.plain = plain; D.spans = spans;

